  fastify.get('/vendors', { preHandler: [authenticate] }, async (request, reply) => {
    const q = exportQuerySchema.parse(request.query)
    const where: Prisma.VendorWhereInput = { active: true }
    if (q.search) where.OR = [
      { name: { contains: q.search, mode: 'insensitive' } },
      { contactName: { contains: q.search, mode: 'insensitive' } },
    ]
    if (q.city) where.city = { equals: q.city, mode: 'insensitive' }
    applyDateFilter(where as any, q.dateFilter, q.dateFrom, q.dateTo, 'IN')

    const vendors = await fastify.prisma.vendor.findMany({
      where,
      include: {
        _count: { select: { stockTransactions: true } },
        stockTransactions: { where: { type: 'IN' }, orderBy: { transactionDate: 'desc' }, take: 1, select: { transactionDate: true, createdAt: true } },
      },
      orderBy: { name: 'asc' },
    })

    const label = todayLabel()
    const headers = ['Company Name', 'Contact Person', 'Phone', 'Email', 'City', 'Address', 'Total Purchases', 'Last Purchase']
    const rows = vendors.map((v) => [
      v.name, v.contactName ?? '', v.phone ?? '', v.email ?? '', v.city ?? '', v.address ?? '',
      v._count.stockTransactions,
      v.stockTransactions[0] ? fmtDate(v.stockTransactions[0].transactionDate ?? v.stockTransactions[0].createdAt) : '',
    ] as (string | number)[])

    if (q.format !== 'xlsx') return sendCsv(reply, headers, rows, `Vendors_${label}.csv`)

    const wb = new ExcelJS.Workbook(); wb.creator = 'Acme Inventory'
    const ws = wb.addWorksheet('Vendors')
    ws.columns = [
      { header: 'Company Name', key: 'name', width: 28 },
      { header: 'Contact Person', key: 'contactName', width: 20 },
      { header: 'Phone', key: 'phone', width: 16 },
      { header: 'Email', key: 'email', width: 28 },
      { header: 'City', key: 'city', width: 14 },
      { header: 'Address', key: 'address', width: 35 },
      { header: 'Total Purchases', key: 'count', width: 16 },
      { header: 'Last Purchase', key: 'last', width: 16 },
    ]
    vendors.forEach((v) => ws.addRow({
      name: v.name, contactName: v.contactName ?? '', phone: v.phone ?? '',
      email: v.email ?? '', city: v.city ?? '', address: v.address ?? '',
      count: v._count.stockTransactions,
      last: v.stockTransactions[0] ? fmtDate(v.stockTransactions[0].transactionDate ?? v.stockTransactions[0].createdAt) : '',
    }))
    styleSheet(ws)
    ws.getColumn('count').alignment = { horizontal: 'right' }
    addFooter(ws, headers.length)
    return sendXlsx(reply, wb, `Vendors_${label}.xlsx`)
  })

