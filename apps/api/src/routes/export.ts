const HEADER_ARGB = 'FF1E1B4B'
const FOOTER_ARGB = 'FF888888'

function fmtDate(val: string | Date | null | undefined): string {
  if (!val) return ''
  return new Date(val).toLocaleDateString('en-US', { day: '2-digit', month: '2-digit', year: 'numeric' })
}

function todayLabel(): string {
  return new Date().toLocaleDateString('en-US', { day: '2-digit', month: '2-digit', year: 'numeric' }).replace(/\//g, '-')
}

function styleSheet(ws: ExcelJS.Worksheet) {
  const headerRow = ws.getRow(1)
  headerRow.height = 22
  headerRow.eachCell((cell: ExcelJS.Cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_ARGB } }
    cell.alignment = { horizontal: 'center', vertical: 'middle' }
    cell.border = { bottom: { style: 'thin', color: { argb: 'FFFFFFFF' } } }
  })
  ws.views = [{ state: 'frozen', xSplit: 0, ySplit: 1, topLeftCell: 'A2', activeCell: 'A2' }]
}

function addFooter(ws: ExcelJS.Worksheet, colCount: number) {
  ws.addRow([])
  const fr = ws.addRow([`Generated by Acme Inventory | ${new Date().toLocaleDateString('en-US')}`])
  const fc = fr.getCell(1)
  fc.font = { italic: true, color: { argb: FOOTER_ARGB }, size: 10 }
  if (colCount > 1) ws.mergeCells(fr.number, 1, fr.number, colCount)
}

async function sendXlsx(reply: any, wb: ExcelJS.Workbook, filename: string) {
  const buffer = await wb.xlsx.writeBuffer()
  reply.header('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
  reply.header('Content-Disposition', `attachment; filename="${filename}"`)
  return reply.send(Buffer.from(buffer as ArrayBuffer))
}

function sendCsv(reply: any, headers: string[], rows: (string | number)[][], filename: string) {
  const lines = [headers, ...rows].map((row) =>
    row.map((c) => `"${String(c ?? '').replace(/"/g, '""')}"`).join(',')
  )
  reply.header('Content-Type', 'text/csv; charset=UTF-8')
  reply.header('Content-Disposition', `attachment; filename="${filename}"`)
  return reply.send('﻿' + lines.join('\r\n'))
}

function applyDateFilter(
  where: Record<string, any>,
  dateFilter: string,
  dateFrom?: string,
  dateTo?: string,
  txType: 'IN' | 'OUT' = 'IN'
) {
  if (dateFilter === 'all') return
  const to = new Date(); to.setHours(23, 59, 59, 999)
  const from = new Date()
  if (dateFilter === '7d') from.setDate(from.getDate() - 7)
  else if (dateFilter === '1m') from.setMonth(from.getMonth() - 1)
  else if (dateFilter === '3m') from.setMonth(from.getMonth() - 3)
  else if (dateFilter === 'custom') {
    if (dateFrom) from.setTime(new Date(dateFrom).getTime())
    if (dateTo) { const d = new Date(dateTo); d.setHours(23, 59, 59, 999); to.setTime(d.getTime()) }
  }
  where.stockTransactions = { some: { type: txType, createdAt: { gte: from, lte: to } } }
}

const exportQuerySchema = z.object({
  format: z.enum(['xlsx', 'csv', 'gsheets']).default('xlsx'),
  search: z.string().optional(),
  city: z.string().optional(),
  dateFilter: z.string().default('all'),
  dateFrom: z.string().optional(),
  dateTo: z.string().optional(),
})

