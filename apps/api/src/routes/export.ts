    if (q.type !== 'ALL') where.type = q.type
    if (q.dateFrom || q.dateTo) {
      where.transactionDate = {}
      if (q.dateFrom) (where.transactionDate as any).gte = new Date(q.dateFrom)
      if (q.dateTo) {
        const d = new Date(q.dateTo); d.setHours(23, 59, 59, 999);
        (where.transactionDate as any).lte = d
      }
    }
    if (q.productSearch) where.product = { name: { contains: q.productSearch, mode: 'insensitive' } }

    const txns = await fastify.prisma.stockTransaction.findMany({
      where,
      include: {
        product: { select: { name: true, sku: true } },
        vendor: { select: { name: true } },
        buyer: { select: { name: true } },
        user: { select: { name: true } },
      },
      orderBy: { transactionDate: 'desc' },
      take: 5000,
    })

    // Build filename with filter context
    let suffix = ''
    if (q.type !== 'ALL') suffix += `_${q.type}`
    if (q.dateFrom && q.dateTo) suffix += `_${fmtDate(q.dateFrom).replace(/\//g, '-')}_to_${fmtDate(q.dateTo).replace(/\//g, '-')}`
    else if (q.dateFrom) suffix += `_From_${fmtDate(q.dateFrom).replace(/\//g, '-')}`
    else if (q.dateTo) suffix += `_To_${fmtDate(q.dateTo).replace(/\//g, '-')}`

